"""Write reports/results.md and reports/figures/*.png from the stored answers."""

from __future__ import annotations

import os

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402

from . import analysis as A  # noqa: E402
from . import config as C  # noqa: E402

COLORS = {"llama3.1-8b": "#d1773a", "qwen2.5-7b": "#3b7dd8", "qwen3-8b": "#5b4fc9", "gemma3-12b": "#2f8f6f"}
LABEL = {"llama3.1-8b": "Llama 3.1 8B", "qwen2.5-7b": "Qwen2.5 7B", "qwen3-8b": "qwen3 8B", "gemma3-12b": "Gemma 3 12B"}
plt.rcParams.update({"font.size": 10, "axes.spines.top": False, "axes.spines.right": False,
                     "axes.titleweight": "bold", "savefig.dpi": 200, "savefig.bbox": "tight"})


def pct(x, digits=1) -> str:
    return "–" if x is None or (isinstance(x, float) and np.isnan(x)) else f"{100 * x:.{digits}f}%"


def pp(x, digits=1) -> str:
    return "–" if x is None or np.isnan(x) else f"{100 * x:+.{digits}f}"


def ci(lo, hi, digits=1) -> str:
    return f"[{100 * lo:+.{digits}f}, {100 * hi:+.{digits}f}]"


def md_table(df: pd.DataFrame) -> str:
    cols = list(df.columns)
    lines = ["| " + " | ".join(str(c) for c in cols) + " |", "|" + "|".join("---" for _ in cols) + "|"]
    lines += ["| " + " | ".join(str(v) for v in row) + " |" for row in df.itertuples(index=False)]
    return "\n".join(lines)


def fig_cliff(acc: pd.DataFrame, path: str):
    """Score against bits per weight, one line per family, one panel per task (extraction: base source)."""
    panels = [("gsm8k", "base", "GSM8K (maths), accuracy"), ("mmlu", "base", "MMLU (multiple choice), accuracy"),
              ("drift", "base", "Extraction, fields right"), ("drift", "reformatted", "Extraction, reformatted source")]
    fig, axes = plt.subplots(1, 4, figsize=(15, 3.9), sharey=False)
    for ax, (task, variant, title) in zip(axes, panels):
        t = acc[(acc.task == task) & (acc.variant == variant) & (acc.level != "qat")]
        for fam, g in t.groupby("family"):
            g = g.sort_values("bits")
            ax.errorbar(g.bits, g.score, yerr=[g.score - g.lo, g.hi - g.score], fmt="-o", ms=4, lw=1.4,
                        capsize=0, color=COLORS[fam], label=LABEL[fam], alpha=0.9)
        q = acc[(acc.task == task) & (acc.variant == variant) & (acc.level == "qat")]
        for r in q.itertuples():
            ax.errorbar([r.bits], [r.score], yerr=[[r.score - r.lo], [r.hi - r.score]], fmt="D", ms=5,
                        color=COLORS[r.family], mfc="white", label=f"{LABEL[r.family]} QAT 4-bit")
        ax.set_xscale("log", base=2)
        ax.set_xticks([3, 4, 5, 6, 8, 16], ["3", "4", "5", "6", "8", "16"])
        ax.minorticks_off()
        ax.set_xlabel("bits per weight")
        ax.set_title(title, fontsize=10)
        ax.yaxis.set_major_formatter(matplotlib.ticker.PercentFormatter(1, decimals=0))
        ax.grid(alpha=0.25)
    h, lab = axes[0].get_legend_handles_labels()
    h2, lab2 = axes[2].get_legend_handles_labels()
    seen = dict(zip(lab, h)) | dict(zip(lab2, h2))
    fig.legend(seen.values(), seen.keys(), loc="lower center", ncol=5, frameon=False, fontsize=9,
               bbox_to_anchor=(0.5, -0.12))
    fig.suptitle("Score by quantization level, with 95% intervals (16 = fp16, the reference)", x=0.01, ha="left",
                 y=1.02)
    fig.savefig(path)
    plt.close(fig)


def fig_agree(ag: pd.DataFrame, path: str):
    fig, axes = plt.subplots(1, 3, figsize=(12, 3.6), sharey=True)
    for ax, task in zip(axes, C.TASKS):
        t = ag[(ag.task == task) & (ag.level != "qat") & (ag.level != C.REFERENCE)]
        for fam, g in t.groupby("family"):
            g = g.assign(bits=g.level.map(C.BITS)).sort_values("bits")
            ax.errorbar(g.bits, g.agree, yerr=[g.agree - g.lo, g.hi - g.agree], fmt="-o", ms=4, lw=1.4,
                        color=COLORS[fam], label=LABEL[fam], alpha=0.9)
        ax.set_xscale("log", base=2)
        ax.set_xticks([3, 4, 5, 6, 8], ["3", "4", "5", "6", "8"])
        ax.minorticks_off()
        ax.set_xlabel("bits per weight")
        ax.set_title(f"{A.TASK_LABEL[task]}", fontsize=10)
        ax.yaxis.set_major_formatter(matplotlib.ticker.PercentFormatter(1, decimals=0))
        ax.grid(alpha=0.25)
    axes[0].set_ylabel("same final answer as fp16")
    axes[0].legend(frameon=False, fontsize=9, loc="lower right")
    fig.suptitle("How often each level gives the same answer as the model's fp16 build", x=0.01, ha="left", y=1.02)
    fig.savefig(path)
    plt.close(fig)


def write_report(split: str = "main"):
    df = A.load(split)
    os.makedirs(C.FIGURES, exist_ok=True)
    sfx = "" if split == "main" else f"_{split}"
    out = [f"# Results ({split} items)", "",
           "Generated by `qcliff report` from `results/answers/`. Intervals are 95% item bootstraps (2,000 "
           "draws). Drops are paired by item against the same model's fp16 build. Extraction is scored as the "
           "share of the 8 fields right per record.", ""]
    acc = A.accuracy_table(df)
    if not len(acc):
        print("no reference level yet")
        return
    fig_cliff(acc, os.path.join(C.FIGURES, f"cliff{sfx}.png"))
    out += ["## Score by level", "", f"![cliff](figures/cliff{sfx}.png)", ""]
    for fam in C.FAMILIES:
        t = acc[acc.family == fam]
        if not len(t):
            continue
        rows = []
        for lv in A.levels_of(df, fam):
            cells = [lv, C.BITS[lv]]
            for task, variant in [("gsm8k", "base"), ("mmlu", "base"), ("drift", "base"), ("drift", "reformatted")]:
                r = t[(t.level == lv) & (t.task == task) & (t.variant == variant)]
                cells.append("–" if not len(r) else f"{pct(r.score.iloc[0])} ({pp(r["diff"].iloc[0])})")
            rows.append(cells)
        out += [f"### {LABEL[fam]} (n = {int(t[t.task == 'gsm8k'].n.max())} per task, {int(t[t.task == 'drift'].n.max())} records)", "",
                "Score, and in brackets the drop from fp16 in points.", "",
                md_table(pd.DataFrame(rows, columns=["level", "bits", "GSM8K", "MMLU", "extraction",
                                                     "extraction (reformatted)"])), ""]
    rows = [[LABEL[r.family], A.TASK_LABEL[r.task] + ("" if r.variant == "base" else f" ({r.variant})"), r.level,
             pp(r.diff), ci(r.diff_lo, r.diff_hi), r.n] for r in acc[acc.level != C.REFERENCE].itertuples()]
    out += ["## Drops from fp16 (pp, paired by item)", "",
            md_table(pd.DataFrame(rows, columns=["model", "task", "level", "drop", "95% CI", "n"])), ""]
    cl = A.cliff_table(acc)
    cl["drop there"] = [pp(x) for x in cl["drop there"]]
    cl["drop at lowest"] = [pp(x) for x in cl["drop at lowest"]]
    out += ["## First clear drop", "",
            "Walking down from fp16, the first level whose drop is at least 5 points with an interval that "
            "excludes zero (QAT left out).", "", md_table(cl), ""]
    ag = A.agreement_table(df)
    fig_agree(ag, os.path.join(C.FIGURES, f"agreement{sfx}.png"))
    rows = [[LABEL[r.family], A.TASK_LABEL[r.task], r.level, pct(r.agree), f"[{100 * r.lo:.1f}, {100 * r.hi:.1f}]", r.n]
            for r in ag.itertuples()]
    out += ["## Same answer as fp16", "", f"![agreement](figures/agreement{sfx}.png)", "",
            md_table(pd.DataFrame(rows, columns=["model", "task", "level", "same answer", "95% CI", "n"])), ""]
    out += ["## Noise floor (A/A: the same prompt sent twice)", "", md_table(A.aa_table(df)), ""]
    out += ["## Validity", "", md_table(A.validity_table(df)), ""]
    sp = A.speed_table(df)
    if len(sp):
        out += ["## Speed and size", "", "Median generation speed on GSM8K replies on this laptop (a rough guide).",
                "", md_table(sp), ""]
    name = "results.md" if split == "main" else f"results_{split}.md"
    with open(os.path.join(C.REPORTS, name), "w") as f:
        f.write("\n".join(out))
    print(f"wrote reports/{name}")
